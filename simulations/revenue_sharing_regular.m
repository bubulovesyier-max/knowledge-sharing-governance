%% Revenue-sharing mode simulation for the knowledge-sharing evolutionary game
% 分成制收费模式下的知识共享演化博弈仿真程序
%
% 策略编码：
% A = 1: supply only        只供给知识，不享用知识
% B = 2: supply and consume 既供给知识，也享用知识
% C = 3: consume only       只享用知识，不供给知识
% D = 4: inactive           不供给也不享用，处于低活跃状态
%
% 本代码采用随机异步更新方式：
% 每一个时间步只随机抽取一个参与者进行一次费米规则更新。
% 每次更新后都记录四类策略比例和平台总收益。
%
% 本代码输出两个图：
% 1. 四类策略比例的演化图
% 2. 平台总收益的演化图
%
% 新增输出：
% 3. 记录最后10%时间段的平台收益
% 4. 将最后10%平台收益输出到Excel文件

clear;      % 清除工作区中的变量，避免旧变量影响本次仿真
clc;        % 清空命令窗口
close all;  % 关闭所有已经打开的图像窗口

%% 1. 基准参数设置
% 这些参数对应论文模型中的基本变量。

params.c = 1.00;        % c：知识供给成本。策略A和策略B需要承担该成本
params.u = 2.00;        % u：知识享用的最大潜在效用，即V(nP)的上限
params.alpha = 0.25;    % alpha：知识吸收效率，决定知识供给数量转化为知识效用的速度
params.hD = 0.5;        % hD：分成制下知识供给者的非货币收益强度
params.p = 0.6;         % p：分成制下知识享用者支付的知识价格
params.theta = 0.6;     % theta：知识供给者获得的交易分成比例
params.kappa = 0.20;    % kappa：费米更新规则中的噪声强度
params.sigma = 0.15;    % sigma：平台间接收益能力系数

L = 50;                 % 二维规则网络边长，网络规模为L×L
N = L * L;              % 参与者总数。这里N=50×50=2500
T = 80000;              % 异步更新时间步数。这里一个时间步表示一次个体策略更新

nReplicates = 10;       % 独立重复仿真次数，用于计算均值和标准误
masterSeed = 20260710;  % 主随机种子，用于保证结果可复现
initialProb = [0.25, 0.25, 0.25, 0.25];  % 初始时刻四类策略的随机分布概率

%% 2. 输出文件夹设置
% 所有结果文件会保存到当前脚本所在目录下的
% results_sharing_async_total_revenue文件夹。

scriptDir = fileparts(mfilename('fullpath'));

% 在命令窗口直接运行或脚本尚未保存时，使用当前工作目录
if isempty(scriptDir)
    scriptDir = pwd;
end

outputDir = fullfile( ...
    scriptDir, ...
    'results_sharing_async_total_revenue');

if ~exist(outputDir, 'dir')
    mkdir(outputDir);
end

%% 3. 多次独立仿真
% allHistory用于保存每次仿真的策略比例演化结果。
% allRevenueHistory用于保存每次仿真的平台总收益演化结果。
% finalStrategies用于保存每次仿真的最终空间策略分布。

allHistory = zeros(T + 1, 4, nReplicates);

allRevenueHistory = zeros( ...
    T + 1, ...
    nReplicates);

finalStrategies = zeros( ...
    L, ...
    L, ...
    nReplicates, ...
    'uint8');

for rIndex = 1:nReplicates

    % 每一次重复仿真使用不同随机种子，
    % 但由同一个主随机种子生成，方便复现
    runSeed = masterSeed + rIndex - 1;

    % 运行一次分成制异步仿真
    [allHistory(:, :, rIndex), ...
     allRevenueHistory(:, rIndex), ...
     finalStrategy] = ...
        simulateSharingModeAsync( ...
            params, ...
            L, ...
            T, ...
            initialProb, ...
            runSeed);

    % 保存该次仿真的最终策略空间分布
    finalStrategies(:, :, rIndex) = ...
        uint8(finalStrategy);

    fprintf('Replicate %d/%d completed.\n', ...
        rIndex, nReplicates);

end

%% 4. 计算均值、标准误和派生指标

meanHistory = mean( ...
